/** Build EGDesk routing headers from env vars (injected into every upstream call). */
function buildEgdeskHeaders(): Record<string, string> {
  const headers: Record<string, string> = { 'Content-Type': 'application/json' };
  const apiKey = process.env.NEXT_PUBLIC_EGDESK_API_KEY;
  const projectId = process.env.NEXT_PUBLIC_EGDESK_PROJECT_ID;
  const egdeskEnv = process.env.NEXT_PUBLIC_EGDESK_ENV;
  if (apiKey) headers['X-Api-Key'] = apiKey;
  if (projectId) headers['X-EGDesk-Project-Id'] = projectId;
  if (egdeskEnv) headers['X-EGDesk-Env'] = egdeskEnv;
  return headers;
}

/** Prefer loopback MCP so proxy hops never re-enter the public tunnel. */
function resolveEgdeskMcpApiUrl(): string {
  const internal = process.env.EGDESK_MCP_INTERNAL_URL;
  if (internal && internal.trim()) return internal.replace(/\/$/, '');
  return (process.env.NEXT_PUBLIC_EGDESK_API_URL || 'http://localhost:8080').replace(/\/$/, '');
}

/**
 * Prefer loopback MCP when EGDESK_MCP_INTERNAL_URL is set (hosted coding on the PC).
 */
function resolveVisitorAuthMcpApiUrl(): string {
  const internal = process.env.EGDESK_MCP_INTERNAL_URL;
  if (internal && internal.trim()) return internal.replace(/\/$/, '');
  const tunnel = process.env.NEXT_PUBLIC_EGDESK_TUNNEL_URL;
  if (tunnel && tunnel.trim()) return tunnel.replace(/\/$/, '');
  const publicUrl = process.env.NEXT_PUBLIC_EGDESK_API_URL;
  if (publicUrl && publicUrl.trim()) return publicUrl.replace(/\/$/, '');
  return 'http://localhost:8080';
}

/** Phase 7b visitor BYO tools must hit desktop MCP (secrets), not the tunnel gateway. */
const VISITOR_AUTH_DESKTOP_ONLY_TOOLS = new Set(['register_gcp', 'gcp_status', 'forget_gcp']);

function resolveVisitorAuthMcpApiUrlForTool(tool: string): string {
  if (VISITOR_AUTH_DESKTOP_ONLY_TOOLS.has(tool)) {
    const internal = process.env.EGDESK_MCP_INTERNAL_URL;
    if (internal && internal.trim()) return internal.replace(/\/$/, '');
    return 'http://localhost:8080';
  }
  return resolveVisitorAuthMcpApiUrl();
}

